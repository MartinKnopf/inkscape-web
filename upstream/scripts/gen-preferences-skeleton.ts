// Upstream: src/preferences-skeleton.h
// Generate packages/core/src/preferences-skeleton.ts from the upstream skeleton.
// Usage: INKSCAPE_SRC=~/dev/inkscape node upstream/scripts/gen-preferences-skeleton.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const src = (process.env.INKSCAPE_SRC ?? join(homedir(), 'dev/inkscape')).replace(/^~/, homedir());
const header = readFileSync(join(src, 'src/preferences-skeleton.h'), 'utf8');
const xml = /R"=====\(([\s\S]*?)\)====="/.exec(header)?.[1];
if (!xml) throw new Error('skeleton not found');

const unescapeXml = (s: string) =>
  s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');

// Every element is a node of the path (its id); its other attributes are values.
// The root element <inkscape> is not part of the path.
const values: [string, string][] = [];
const stack: string[] = [];
let depth = 0;
for (const m of xml
  .replace(/<!--[\s\S]*?-->/g, '')
  .matchAll(/<(\/?)([a-zA-Z]+)((?:[^>"]|"[^"]*")*?)(\/?)>/g)) {
  const [, closing, , attrs, selfClosing] = m;
  if (closing) {
    depth--;
    if (depth > 0) stack.pop();
    continue;
  }
  const attributes = [...(attrs ?? '').matchAll(/([\w.:-]+)\s*=\s*"([^"]*)"/g)].map(
    (a) => [a[1] as string, unescapeXml(a[2] as string)] as const,
  );
  const id = attributes.find(([k]) => k === 'id')?.[1] ?? '';
  const path = [...stack, id].join('/');
  if (depth > 0) for (const [k, v] of attributes) if (k !== 'id') values.push([`/${path}/${k}`, v]);
  if (selfClosing) continue;
  if (depth > 0) stack.push(id);
  depth++;
}

const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const out = `// SPDX-License-Identifier: GPL-2.0-or-later
// Upstream: src/preferences-skeleton.h
// Generated by upstream/scripts/gen-preferences-skeleton.ts; do not edit.
/*
 * Authors: see git history
 *
 * Copyright (C) 2018 Authors
 */

/**
 * Default preference values, by path, from the upstream skeleton
 * ('<group id="tools"><group id="shapes" style="..."/>' is "/tools/shapes/style").
 * Preferences returns them when the user has not set a value.
 */
export const preferences_skeleton: Readonly<Record<string, string>> = {
${values.map(([k, v]) => `  ${quote(k)}: ${quote(v)},`).join('\n')}
};
`;
writeFileSync(join(import.meta.dirname, '../../packages/core/src/preferences-skeleton.ts'), out);
console.log(`${values.length} preferences`);
