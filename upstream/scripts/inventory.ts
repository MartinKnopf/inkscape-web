// Parity inventory: list upstream features and check which ones we have ported.
//
//   pnpm upstream:inventory           print the summary
//   pnpm upstream:inventory --write   also write docs/PARITY.md
//
// An item counts as ported when our code (packages/*, apps/*) refers to it:
// - "header" items: the upstream file is named in an "Upstream:" header.
// - "literal" items: the upstream key appears as a string literal
//   (action ids, dialog keys, LPE keys).
// - "loaded" items: the item is in a list that the category computes (Python extensions: the
//   extension system loads the .inx and can run its script, see extensionIsLoaded()).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { checkUpstream, ourSources, repoRoot, sync, upstreamReferences, upstreamRoot } from './upstream.ts';

interface Category {
  name: string;
  match: 'header' | 'literal' | 'loaded';
  /** Upstream paths ('header') or keys ('literal', 'loaded'). */
  items: string[];
  /** The items that count as ported, for 'loaded'. */
  loaded?: Set<string>;
}

const src = (p: string) => readFileSync(join(upstreamRoot, p), 'utf8');
const ls = (dir: string, re: RegExp) =>
  readdirSync(join(upstreamRoot, dir))
    .filter((f) => re.test(f))
    .map((f) => `${dir}/${f}`)
    .sort();
const unique = (a: string[]) => [...new Set(a)].sort();

/**
 * Whether the extension system loads the .inx and can run it. packages/assets/build.ts serves
 * every .inx of share/extensions; build_from_reprdoc() (packages/editor/src/extension/system.ts)
 * takes input, output, effect and template extensions with a script, and skips ids with "win32"; the script
 * runs in Pyodide, so its interpreter must be python (or none). XSLT and plugin extensions are not
 * loaded.
 */
function extensionIsLoaded(inx: string, id: string): boolean {
  return (
    /<(input|output|effect|template)[\s>]/.test(inx) &&
    /<script[\s>]/.test(inx) &&
    !/interpreter="(?!python")/.test(inx) &&
    !id.includes('win32')
  );
}

function categories(): Category[] {
  const actions = ls('src/actions', /\.cpp$/).flatMap((f) =>
    [...src(f).matchAll(/"((?:app|win|doc)\.[a-z0-9-]+)/g)].map((m) => m[1]!),
  );
  const dialogs = [...src('src/ui/dialog/dialog-data.cpp').matchAll(/\{\s*"([A-Za-z]+)",\s*_\(/g)].map(
    (m) => m[1]!,
  );
  const lpeBlock = src('src/live_effects/effect.cpp').split('LPETypeData[] = {')[1]!.split('\n};')[0]!;
  const lpes = [...lpeBlock.matchAll(/NC_\("path effect",\s*"[^"]+"\)\s*,[^\n]*\n\s*"([a-z0-9_]+)"/g)].map(
    (m) => m[1]!,
  );
  const extensions = ls('share/extensions', /\.inx$/).flatMap((f) => {
    const text = src(f);
    const id = /<id>([^<]+)<\/id>/.exec(text)?.[1];
    return id ? [{ id, loaded: extensionIsLoaded(text, id) }] : [];
  });
  return [
    { name: 'Tools', match: 'header', items: ls('src/ui/tools', /-tool\.cpp$/) },
    { name: 'Dialogs', match: 'literal', items: unique(dialogs) },
    { name: 'Actions', match: 'literal', items: unique(actions) },
    { name: 'Live path effects', match: 'literal', items: unique(lpes) },
    {
      name: 'Internal import/export modules',
      match: 'header',
      items: ls('src/extension/internal', /\.cpp$/),
    },
    {
      name: 'Python extensions',
      match: 'loaded',
      items: unique(extensions.map((e) => e.id)),
      loaded: new Set(extensions.filter((e) => e.loaded).map((e) => e.id)),
    },
  ];
}

checkUpstream();
const refs = upstreamReferences();
const ours = ourSources()
  .map((f) => readFileSync(f, 'utf8'))
  .join('\n');
const isPorted = (c: Category, item: string) =>
  c.match === 'header'
    ? refs.has(item)
    : c.match === 'loaded'
      ? !!c.loaded?.has(item)
      : [`'${item}'`, `"${item}"`, `\`${item}\``].some((q) => ours.includes(q));

const cats = categories();
const rows = cats.map((c) => {
  const done = c.items.filter((i) => isPorted(c, i)).length;
  return { c, done, pct: c.items.length ? Math.round((100 * done) / c.items.length) : 0 };
});

const summary = [
  '| Category | Ported | Total | % |',
  '|---|---:|---:|---:|',
  ...rows.map((r) => `| ${r.c.name} | ${r.done} | ${r.c.items.length} | ${r.pct} |`),
].join('\n');
console.log(summary);

if (process.argv.includes('--write')) {
  const lists = rows.map(
    (r) =>
      `<details><summary>${r.c.name} (${r.done}/${r.c.items.length})</summary>\n\n` +
      r.c.items
        .map((i) => `- [${isPorted(r.c, i) ? 'x' : ' '}] \`${r.c.match === 'header' ? basename(i) : i}\``)
        .join('\n') +
      '\n\n</details>',
  );
  const md = `# Parity with upstream Inkscape

Generated by \`pnpm upstream:inventory --write\`. Do not edit.
Upstream commit: \`${sync.commit}\`.

${summary}

${lists.join('\n\n')}
`;
  writeFileSync(join(repoRoot, 'docs/PARITY.md'), md);
  console.log('wrote docs/PARITY.md');
}
