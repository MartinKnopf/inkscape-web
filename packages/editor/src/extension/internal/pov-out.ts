import {
  Colors,
  is_straight_curve,
  N_,
  pathv_to_linear_and_cubic_beziers,
  type SPDocument,
  SPItem,
  type SPObject,
  SPShape,
} from '@inkscape-web/core';
import { CubicBezier, Rect } from '@inkscape-web/geom';
import { INKSCAPE_VERSION } from '../../actions/actions-base.ts';
import { Implementation } from '../implementation/implementation.ts';
import type { Output } from '../output.ts';
import { INKSCAPE_EXTENSION_URI } from '../prefdialog/widget.ts';
import { build_from_mem } from '../system.ts';

function err(message: string): void {
  console.warn(`Pov-out err: ${message}`);
}

/** The opacity of the item times the opacity of its ancestors (upstream effective_opacity). */
function effective_opacity(item: SPItem): number {
  let ret = 1.0;
  for (let obj: SPObject | null = item; obj; obj = obj.parent) ret *= obj.style.opacity.as_double();
  return ret;
}

/** We want to control floating output format (upstream dstr: "%.8f"). */
function dstr(d: number): string {
  return d.toFixed(8);
}

/** The time as ctime() prints it, with a new line: "Thu Nov  5 08:00:00 2026". */
function ctime(date: Date): string {
  const day = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'][date.getDay()];
  const month = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][
    date.getMonth()
  ];
  const p2 = (n: number) => String(n).padStart(2, '0');
  const time = `${p2(date.getHours())}:${p2(date.getMinutes())}:${p2(date.getSeconds())}`;
  return `${day} ${month} ${String(date.getDate()).padStart(2, ' ')} ${time} ${date.getFullYear()}\n`;
}

interface PovShapeInfo {
  id: string;
  color: string;
}

/** The PovRay output: bezier prisms of the shapes (upstream PovOutput). */
export class PovOutput extends Implementation {
  #outbuf = '';
  #nrNodes = 0;
  #nrSegments = 0;
  #nrShapes = 0;
  #idIndex = 0;
  #minx = 0;
  #miny = 0;
  #maxx = 0;
  #maxy = 0;
  #povShapes: PovShapeInfo[] = [];

  /** Output data to the buffer. */
  #out(text: string): void {
    this.#outbuf += text;
  }

  #vec2(a: number, b: number): string {
    return `<${dstr(a)}, ${dstr(b)}>`;
  }

  /** Output one bezier's start, start-control, end-control, and end nodes. */
  #segment(
    segNr: number,
    p: readonly [number, number, number, number, number, number, number, number],
  ): void {
    this.#out(
      `    /*${String(segNr).padStart(4, ' ')}*/ ` +
        `${this.#vec2(p[0], p[1])}, ${this.#vec2(p[2], p[3])}, ${this.#vec2(p[4], p[5])}, ${this.#vec2(p[6], p[7])}`,
    );
  }

  /** Output the file header. */
  #doHeader(): boolean {
    this.#out('/*###################################################################\n');
    this.#out('### This PovRay document was generated by Inkscape\n');
    this.#out('### http://www.inkscape.org\n');
    this.#out(`### Created: ${ctime(new Date())}`);
    this.#out(`### Version: ${INKSCAPE_VERSION}\n`);
    this.#out('#####################################################################\n');
    this.#out('### NOTES:\n');
    this.#out('### ============\n');
    this.#out('### POVRay information can be found at\n');
    this.#out('### http://www.povray.org\n');
    this.#out('###\n');
    this.#out("### The 'AllShapes' objects at the bottom are provided as a\n");
    this.#out('### preview of how the output would look in a trace.  However,\n');
    this.#out('### the main intent of this file is to provide the individual\n');
    this.#out('### shapes for inclusion in a POV project.\n');
    this.#out('###\n');
    this.#out('### For an example of how to use this file, look at\n');
    this.#out('### share/examples/istest.pov\n');
    this.#out('###\n');
    this.#out('### If you have any problems with this output, please see the\n');
    this.#out('### Inkscape project at http://www.inkscape.org, or visit\n');
    this.#out('### the #inkscape channel on irc.freenode.net . \n');
    this.#out('###\n');
    this.#out('###################################################################*/\n');
    this.#out('\n\n');
    this.#out('/*###################################################################\n');
    this.#out('##   Exports in this file\n');
    this.#out('##==========================\n');
    this.#out(`##    Shapes   : ${this.#nrShapes}\n`);
    this.#out(`##    Segments : ${this.#nrSegments}\n`);
    this.#out(`##    Nodes    : ${this.#nrNodes}\n`);
    this.#out('###################################################################*/\n');
    this.#out('\n\n\n');
    return true;
  }

  /** Output the file footer. */
  #doTail(): boolean {
    this.#out('\n\n');
    this.#out('/*###################################################################\n');
    this.#out('### E N D    F I L E\n');
    this.#out('###################################################################*/\n');
    this.#out('\n\n');
    return true;
  }

  /** Output the curve data to the buffer. */
  #doCurve(item: SPItem, id: string): boolean {
    // Allow all shapes
    if (!(item instanceof SPShape)) return true;

    const curve = item.curve();
    if (!curve || curve.every((p) => p.empty())) return true;

    this.#nrShapes++;

    const shapeInfo: PovShapeInfo = { id, color: '' };

    // Try to get the fill color of the shape
    const style = item.style;
    // fixme: Handle other fill types, even if this means translating gradients to a single flat colour.
    if (style.fill.isColor()) {
      const rgba = style.fill.getColor().converted(Colors.SpaceType.RGB);
      if (rgba) {
        rgba.addOpacity(style.fill_opacity.as_double());
        rgba.addOpacity(effective_opacity(item));
        shapeInfo.color = `rgbf <${dstr(rgba.get(0))}, ${dstr(rgba.get(1))}, ${dstr(rgba.get(2))}, ${dstr(1.0 - rgba.getOpacity())}>`;
      }
    }

    this.#povShapes.push(shapeInfo); // passed all tests. save the info

    // convert the path to only lineto's and cubic curveto's:
    const tf = item.i2dtAffine();
    const pathv = pathv_to_linear_and_cubic_beziers(curve.map((p) => p.transformed(tf)));

    // We need to know the number of segments (NR_CURVETOs/LINETOs, including closing line
    // segment) before we write out segment data. Since we are going to skip degenerate (zero
    // length) paths, we need to loop over all subpaths and segments first.
    let segmentCount = 0;
    for (const pit of pathv) {
      // For all segments in the subpath, including extra closing segment defined by 2geom
      for (const cit of pit.curves()) if (!cit.isDegenerate()) ++segmentCount;
    }

    this.#out('/*###################################################\n');
    this.#out(`### PRISM:  ${id}\n`);
    this.#out('###################################################*/\n');
    this.#out(`#declare ${id} = prism {\n`);
    this.#out('    linear_sweep\n');
    this.#out('    bezier_spline\n');
    this.#out('    1.0, //top\n');
    this.#out('    0.0, //bottom\n');
    this.#out(`    ${segmentCount * 4} //nr points\n`);
    let segmentNr = 0;

    this.#nrSegments += segmentCount;

    const first = pathv[0]?.initialPoint();
    if (!first) return true;
    let cminmax = new Rect(first, first);

    for (const pit of pathv) {
      cminmax = cminmax.expandTo(pit.initialPoint());

      for (const cit of pit.curves()) {
        // Skip zero length segments
        if (cit.isDegenerate()) continue;

        if (is_straight_curve(cit)) {
          const p0 = cit.initialPoint();
          const p1 = cit.finalPoint();
          this.#segment(segmentNr++, [p0.x, p0.y, p0.x, p0.y, p1.x, p1.y, p1.x, p1.y]);
          this.#nrNodes += 8;
        } else if (cit instanceof CubicBezier) {
          const pts = cit.controlPoints();
          const [p0, p1, p2, p3] = [pts[0]!, pts[1]!, pts[2]!, pts[3]!];
          this.#segment(segmentNr++, [p0.x, p0.y, p1.x, p1.y, p2.x, p2.y, p3.x, p3.y]);
          this.#nrNodes += 8;
        } else {
          err('logical error, because pathv_to_linear_and_cubic_beziers was used');
          return false;
        }

        this.#out(segmentNr < segmentCount ? ',\n' : '\n');
        if (segmentNr > segmentCount) {
          err('Too many segments');
          return false;
        }

        cminmax = cminmax.expandTo(cit.finalPoint());
      }
    }

    this.#out('}\n');

    const cminx = cminmax.min().x;
    const cmaxx = cminmax.max().x;
    const cminy = cminmax.min().y;
    const cmaxy = cminmax.max().y;

    this.#out(`#declare ${id}_MIN_X    = ${dstr(cminx)};\n`);
    this.#out(`#declare ${id}_CENTER_X = ${dstr((cmaxx + cminx) / 2.0)};\n`);
    this.#out(`#declare ${id}_MAX_X    = ${dstr(cmaxx)};\n`);
    this.#out(`#declare ${id}_WIDTH    = ${dstr(cmaxx - cminx)};\n`);
    this.#out(`#declare ${id}_MIN_Y    = ${dstr(cminy)};\n`);
    this.#out(`#declare ${id}_CENTER_Y = ${dstr((cmaxy + cminy) / 2.0)};\n`);
    this.#out(`#declare ${id}_MAX_Y    = ${dstr(cmaxy)};\n`);
    this.#out(`#declare ${id}_HEIGHT   = ${dstr(cmaxy - cminy)};\n`);
    if (shapeInfo.color.length > 0) this.#out(`#declare ${id}_COLOR    = ${shapeInfo.color};\n`);
    this.#out('/*###################################################\n');
    this.#out(`### end ${id}\n`);
    this.#out('###################################################*/\n\n\n\n');

    if (cminx < this.#minx) this.#minx = cminx;
    if (cmaxx > this.#maxx) this.#maxx = cmaxx;
    if (cminy < this.#miny) this.#miny = cminy;
    if (cmaxy > this.#maxy) this.#maxy = cmaxy;

    return true;
  }

  /** Descend the svg tree recursively, translating data. */
  #doTreeRecursive(doc: SPDocument, obj: SPObject): boolean {
    const id = obj.getId() ?? `id${this.#idIndex++}`;

    if (obj instanceof SPItem && !this.#doCurve(obj, id)) return false;

    // Descend into children
    for (const child of obj.children) if (!this.#doTreeRecursive(doc, child)) return false;
    return true;
  }

  /** Output the curve data to the buffer. */
  #doTree(doc: SPDocument): boolean {
    const bignum = 1000000.0;
    this.#minx = bignum;
    this.#maxx = -bignum;
    this.#miny = bignum;
    this.#maxy = -bignum;

    if (!this.#doTreeRecursive(doc, doc.getRoot())) return false;

    // Let's make a union of all of the Shapes
    if (this.#povShapes.length) {
      const id = 'AllShapes';
      const pfx = id;
      const o = (s: string) => this.#out(s);
      o('/*###################################################\n');
      o('### UNION OF ALL SHAPES IN DOCUMENT\n');
      o('###################################################*/\n');
      o('\n\n');
      o('/**\n');
      o(' * Allow the user to redefine the finish{}\n');
      o(' * by declaring it before #including this file\n');
      o(' */\n');
      o(`#ifndef (${pfx}_Finish)\n`);
      o(`#declare ${pfx}_Finish = finish {\n`);
      o('    phong 0.5\n');
      o('    reflection 0.3\n');
      o('    specular 0.5\n');
      o('}\n');
      o('#end\n');
      o('\n\n');
      o(`#declare ${id} = union {\n`);
      for (const povShape of this.#povShapes) {
        o(`    object { ${povShape.id}\n`);
        o('        texture { \n');
        o(
          povShape.color.length > 0
            ? `            pigment { ${povShape.color} }\n`
            : '            pigment { rgb <0,0,0> }\n',
        );
        o(`            finish { ${pfx}_Finish }\n`);
        o('            } \n');
        o('        } \n');
      }
      o('}\n\n\n\n');

      const zinc = 0.2 / this.#povShapes.length;
      o('/*#### Same union, but with Z-diffs (actually Y in pov) ####*/\n');
      o('\n\n');
      o('/**\n');
      o(' * Allow the user to redefine the Z-Increment\n');
      o(' */\n');
      o('#ifndef (AllShapes_Z_Increment)\n');
      o(`#declare AllShapes_Z_Increment = ${dstr(zinc)};\n`);
      o('#end\n');
      o('\n');
      o('#declare AllShapes_Z_Scale = 1.0;\n');
      o('\n\n');
      o(`#declare ${pfx}_Z = union {\n`);

      for (const povShape of this.#povShapes) {
        o(`    object { ${povShape.id}\n`);
        o('        texture { \n');
        o(
          povShape.color.length > 0
            ? `            pigment { ${povShape.color} }\n`
            : '            pigment { rgb <0,0,0> }\n',
        );
        o(`            finish { ${pfx}_Finish }\n`);
        o('            } \n');
        o(`        scale <1, ${pfx}_Z_Scale, 1>\n`);
        o('        } \n');
        o(`#declare ${pfx}_Z_Scale = ${pfx}_Z_Scale + ${pfx}_Z_Increment;\n\n`);
      }

      o('}\n');

      const minx = this.#minx;
      const maxx = this.#maxx;
      const miny = this.#miny;
      const maxy = this.#maxy;
      o(`#declare ${pfx}_MIN_X    = ${dstr(minx)};\n`);
      o(`#declare ${pfx}_CENTER_X = ${dstr((maxx + minx) / 2.0)};\n`);
      o(`#declare ${pfx}_MAX_X    = ${dstr(maxx)};\n`);
      o(`#declare ${pfx}_WIDTH    = ${dstr(maxx - minx)};\n`);
      o(`#declare ${pfx}_MIN_Y    = ${dstr(miny)};\n`);
      o(`#declare ${pfx}_CENTER_Y = ${dstr((maxy + miny) / 2.0)};\n`);
      o(`#declare ${pfx}_MAX_Y    = ${dstr(maxy)};\n`);
      o(`#declare ${pfx}_HEIGHT   = ${dstr(maxy - miny)};\n`);
      o('/*##############################################\n');
      o(`### end ${id}\n`);
      o('##############################################*/\n');
      o('\n\n');
    }

    return true;
  }

  /** Set values back to initial state. */
  #reset(): void {
    this.#nrNodes = 0;
    this.#nrSegments = 0;
    this.#nrShapes = 0;
    this.#idIndex = 0;
    this.#outbuf = '';
    this.#povShapes = [];
  }

  /** The PovRay spline definitions of the shapes of an Inkscape SVG file; null if it fails. */
  saveDocument(doc: SPDocument, filename: string): string | null {
    this.#reset();

    // Let's do the curves first, to get the stats
    if (!this.#doTree(doc)) {
      err(`Could not output curves for ${filename}`);
      return null;
    }

    const curveBuf = this.#outbuf;
    this.#outbuf = '';

    if (!this.#doHeader()) {
      err(`Could not write header for ${filename}`);
      return null;
    }

    this.#outbuf += curveBuf;

    if (!this.#doTail()) {
      err(`Could not write footer for ${filename}`);
      return null;
    }
    return this.#outbuf;
  }

  /** Save the document as PovRay shapes. */
  override async save(_mod: Output, doc: SPDocument, filename: string): Promise<Uint8Array | null> {
    const text = this.saveDocument(doc, filename);
    return text === null ? null : new TextEncoder().encode(text);
  }

  /** The definition of the PovRay output (upstream PovOutput::init). */
  static init(): void {
    build_from_mem(
      `<inkscape-extension xmlns="${INKSCAPE_EXTENSION_URI}">\n` +
        `<name>${N_('PovRay Output')}</name>\n` +
        '<id>org.inkscape.output.pov</id>\n' +
        '<output>\n' +
        '<extension>.pov</extension>\n' +
        '<mimetype>text/x-povray-script</mimetype>\n' +
        `<filetypename>${N_('PovRay (*.pov) (paths and shapes only)')}</filetypename>\n` +
        `<filetypetooltip>${N_('PovRay Raytracer File')}</filetypetooltip>\n` +
        '</output>\n' +
        '</inkscape-extension>',
      new PovOutput(),
    );
  }
}
