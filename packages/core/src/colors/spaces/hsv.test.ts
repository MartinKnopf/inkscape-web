import { describe, expect, it } from 'vitest';
import { SpaceType as T } from './enum.ts';
import {
  badColorStringTests,
  componentIds,
  convertTests,
  fromStringTests,
  normalizeTests,
  randomPassthrough,
  toStringTests,
} from './testbase.ts';

describe('HSV', () => {
  fromStringTests([
    // Taken from the w3c hwb example chart
    ['hwb(0 20 20)', [0.0, 0.75, 0.8], 0xcc3333ff],
    ['hwb(30 20.0 20.0)', [0.083, 0.75, 0.8], 0xcc7f33ff],
    ['hwb(90 20 20)', [0.25, 0.75, 0.8], 0x80cc33ff],
    ['hwb(0 40 40)', [0.0, 0.333, 0.6], 0x996666ff],
    ['hwb(30deg 40 40)', [0.083, 0.333, 0.6], 0x997f66ff],
    ['hwb(0.25turn 40 40)', [0.25, 0.333, 0.6], 0x809966ff],
    ['hwb(0 60 60%)', [0.0, 0, 0.5], 0x808080ff],
    ['   hwb(90 60 60)   ', [0.25, 0, 0.5], 0x808080ff],
    ['hwb(0 100 100 / 0.5)', [0.0, 0, 0.5, 0.5], 0x80808080],
  ]);

  badColorStringTests(['hwb', 'hwb(', 'hwb(360,']);

  toStringTests([
    [T.HSV, [0.333, 0.2, 0.8], 'hwb(119 64 20)'],
    [T.HSV, [0.333, 0.8, 0.258], 'hwb(119 5.16 74.2)'],
    [T.HSV, [1.0, 0.5, 0.004], 'hwb(360 0.2 99.6)'],
    [T.HSV, [0, 1, 0.2, 0.8], 'hwb(0 0 80 / 80%)'],
    [T.HSV, [0, 1, 0.2, 0.8], 'hwb(0 0 80)', false],
  ]);

  convertTests([
    // random tests generated by python3 colorsys.rgb_to_hsv()
    [T.HSV, [0.132, 0.333, 0.633], T.RGB, [0.633, 0.59, 0.422]],
    [T.HSV, [0.59, 0.814, 0.225], T.RGB, [0.042, 0.126, 0.225]],
    [T.HSV, [0.351, 0.643, 0.888], T.RGB, [0.317, 0.888, 0.379]],
    [T.HSV, [0.322, 0.639, 0.043], T.RGB, [0.017, 0.043, 0.016], false],
    // No conversion
    [T.HSV, [1.0, 0.4, 0.2], T.HSV, [1.0, 0.4, 0.2]],
  ]);

  normalizeTests([
    [T.HSV, [1.2, 1.2, 1.2, 1.2], [0.2, 1.0, 1.0, 1.0]],
    [T.HSV, [-0.2, -0.2, -0.2, -0.2], [0.8, 0.0, 0.0, 0.0]],
  ]);

  it('converts random colors back and forth', () => randomPassthrough(T.HSV, T.RGB, 1000));

  it('has components', () => expect(componentIds(T.HSV)).toEqual(['h', 's', 'v']));
});
