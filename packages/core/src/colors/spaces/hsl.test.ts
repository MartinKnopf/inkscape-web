import { describe, expect, it } from 'vitest';
import { SpaceType as T } from './enum.ts';
import {
  badColorStringTests,
  componentIds,
  convertTests,
  fromStringTests,
  normalizeTests,
  randomPassthrough,
  toStringTests,
} from './testbase.ts';

describe('HSL', () => {
  fromStringTests([
    ['hsl(80, 100, 50)', [0.222, 1, 0.5], 0xaaff00ff],
    ['hsl(360, 50, 0)', [1.0, 0.5, 0], 0x000000ff],
    ['hsl(180deg, 100%, 50%)', [0.5, 1, 0.5], 0x00ffffff],
    ['hsl(0.5turn 100% 50%)', [0.5, 1, 0.5], 0x00ffffff],
    ['hsl(0.5turn 100  50)', [0.5, 1, 0.5], 0x00ffffff],
    ['   hsl(20,  100,  50)', [0.055, 1, 0.5], 0xff5500ff],
    ['hsl(50% 100% 50% / 50%)', [0.5, 1, 0.5, 0.5], 0x00ffff80],
    ['hsla(30, 0,  50, 0.5)', [0.083, 0, 0.5, 0.5], 0x80808080],
    ['hsla(30  0   50 / 0.5)', [0.083, 0, 0.5, 0.5], 0x80808080],
    ['hsla(30  0   50)', [0.083, 0, 0.5], 0x808080ff],
  ]);

  badColorStringTests(['hsl', 'hsl(', 'hsl(360,']);

  toStringTests([
    [T.HSL, [0.333, 0.2, 0.8], 'hsl(119, 20%, 80%)'],
    [T.HSL, [0.333, 0.8, 0.258], 'hsl(119, 80%, 25.8%)'],
    [T.HSL, [1.0, 0.5, 0.004], 'hsl(360, 50%, 0.4%)'],
    [T.HSL, [0, 1, 0.2, 0.8], 'hsla(0, 100%, 20%, 0.8)', true],
    [T.HSL, [0, 1, 0.2, 0.8], 'hsl(0, 100%, 20%)', false],
  ]);

  convertTests([
    // random tests generated by python3 colorsys.hls_to_rgb()
    [T.HSL, [0.248, 0.225, 0.453], T.RGB, [0.455, 0.554, 0.351]],
    [T.HSL, [0.257, 0.011, 0.403], T.RGB, [0.403, 0.407, 0.399], false],
    [T.HSL, [0.415, 0.514, 0.565], T.RGB, [0.341, 0.789, 0.561]],
    [T.HSL, [0.528, 0.949, 0.408], T.RGB, [0.021, 0.664, 0.795]],
    [T.HSL, [0.942, 0.401, 0.881], T.RGB, [0.929, 0.833, 0.866]],
    // biome-ignore lint/suspicious/noApproximativeNumericConstant: test data
    [T.HSL, [0.845, 0.925, 0.707], T.RGB, [0.978, 0.436, 0.942]],
    // No conversion
    [T.HSL, [1.0, 0.4, 0.2], T.HSL, [1.0, 0.4, 0.2]],
  ]);

  normalizeTests([
    // Note HSL is special in that it's hue component is radial so -0.2 == +0.8
    [T.HSL, [0.5, 0.5, 0.5, 0.5], [0.5, 0.5, 0.5, 0.5]],
    [T.HSL, [1.2, 1.2, 1.2, 1.2], [0.2, 1.0, 1.0, 1.0]],
    [T.HSL, [-0.2, -0.2, -0.2, -0.2], [0.8, 0.0, 0.0, 0.0]],
  ]);

  it('converts random colors back and forth', () => randomPassthrough(T.HSL, T.RGB, 1000));

  it('has components', () => expect(componentIds(T.HSL)).toEqual(['h', 's', 'l']));
});
