import { describe, expect, it } from 'vitest';
import { SpaceType as T } from './enum.ts';
import { Luv } from './luv.ts';
import { componentIds, convertTests, normalizeTests, randomPassFunc, randomPassthrough } from './testbase.ts';

describe('Luv', () => {
  convertTests([
    // No conversion
    [T.LUV, [1.0, 0.4, 0.2], T.LUV, [1.0, 0.4, 0.2]],
  ]);

  normalizeTests([
    [T.LUV, [1.2, 1.2, 1.2, 1.2], [1.0, 1.0, 1.0, 1.0]],
    [T.LUV, [-0.2, -0.2, -0.2, -0.2], [0.0, 0.0, 0.0, 0.0]],
  ]);

  it('converts random colors back and forth', () => {
    // Isolate conversion functions
    randomPassFunc(Luv.profileToSpace, Luv.spaceToProfile, 1000);
    randomPassthrough(T.LUV, T.XYZ, 1000);
  });

  it('has components', () => expect(componentIds(T.LUV)).toEqual(['l', 'u', 'v']));
});

describe('HSLuv', () => {
  convertTests([
    // No conversion
    [T.HSLUV, [1.0, 0.4, 0.2], T.HSLUV, [1.0, 0.4, 0.2]],
    // Generated by hsluv.org a sample of low and high saturation hues
    [T.HSLUV, [0.946, 0.182, 0.5], T.RGB, [0.565, 0.431, 0.49]],
    [T.HSLUV, [0.016, 0.723, 0.5], T.RGB, [0.835, 0.247, 0.349]],
    [T.HSLUV, [0.76, 0.787, 0.5], T.RGB, [0.517, 0.372, 0.878]],
    [T.HSLUV, [0.748, 0.768, 0.232], T.RGB, [0.207, 0.137, 0.549]],
    [T.HSLUV, [0.018, 0.752, 0.232], T.RGB, [0.415, 0.094, 0.149]],
    [T.HSLUV, [0.358, 0.454, 0.232], T.RGB, [0.149, 0.239, 0.152]],
    [T.HSLUV, [0.344, 0.821, 0.848], T.RGB, [0.458, 0.933, 0.352]],
    [T.HSLUV, [0.874, 0.526, 0.848], T.RGB, [0.921, 0.792, 0.901]],
    [T.HSLUV, [0.205, 0.788, 0.848], T.RGB, [0.921, 0.831, 0.384]],
  ]);

  normalizeTests([
    [T.HSLUV, [1.2, 1.2, 1.2, 1.2], [0.2, 1.0, 1.0, 1.0]],
    [T.HSLUV, [-0.2, -0.2, -0.2, -0.2], [0.8, 0.0, 0.0, 0.0]],
  ]);

  it('has components', () => expect(componentIds(T.HSLUV)).toEqual(['h', 's', 'l']));
});
